#include <dolphin/types.h>

typedef void (*MenuFunc)();

// One menu definition (28 bytes), indexed by menu id.
typedef struct MenuDataEntry {
    u8 kind;             // 0x00 high 3 bits = item table (0 item, 1 MX, 2 tool, 3 debug, 4 pda, 5 BT, 6 XD)
    u8 flags1;           // 0x01
    u8 flags2;           // 0x02
    u8 dispMax;          // 0x03
    u8 unk4;             // 0x04
    u8 unk5;             // 0x05
    u16 itemIndex;       // 0x06 first entry in the item table
    s16 x;               // 0x08
    s16 y;               // 0x0A
    MenuFunc cursor;     // 0x0C
    MenuFunc button;     // 0x10
    MenuFunc ctrl;       // 0x14
    MenuFunc draw;       // 0x18
} MenuDataEntry;

