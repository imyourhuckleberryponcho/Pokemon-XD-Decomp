static inline u8 _hexDigit(char c) {
    switch (c) {
    case '0':
    case '1':
    case '2':
    case '3':
    case '4':
    case '5':
    case '6':
    case '7':
    case '8':
    case '9':
        return c - '0';
    case 'a':
    case 'b':
    case 'c':
    case 'd':
    case 'e':
    case 'f':
        return c - 'a' + 10;
    case 'A':
    case 'B':
    case 'C':
    case 'D':
    case 'E':
    case 'F':
        return c - 'A' + 10;
    default:
        return 0;
    }
}

static u32 _primRenderBuf(f32 x, f32 y, char* str, u32 len, bool write) {
    u32 count = 0;
    while (len--) {
        switch (*str) {
        case '\r':
        case '\n':
            break;
        case '|':
            if (write == true) {
                _primTextColor.r = (_hexDigit(str[1]) << 4) | _hexDigit(str[2]);
                _primTextColor.g = (_hexDigit(str[3]) << 4) | _hexDigit(str[4]);
                _primTextColor.b = (_hexDigit(str[5]) << 4) | _hexDigit(str[6]);
            }
            len -= 6;
            str += 6;
            break;
        default: {
            u8* p = _primChar2Ptr(*str);
            int n = *p++;
            int i = n;
            count += n;
            if (write == true) {
                while (i--) {
                    int a = p[0];
                    int b = p[1];
                    p += 2;
                    GXWGFifo.f32 = (0.11f * (a >> 4)) * _primTextXpel + x;
                    GXWGFifo.f32 = (0.11f * (a & 0xF)) * _primTextYpel + y;
                    GXWGFifo.u8 = _primTextColor.r;
                    GXWGFifo.u8 = _primTextColor.g;
                    GXWGFifo.u8 = _primTextColor.b;
                    GXWGFifo.u8 = _primTextColor.a;
                    GXWGFifo.f32 = (0.11f * (b >> 4)) * _primTextXpel + x;
                    GXWGFifo.f32 = (0.11f * (b & 0xF)) * _primTextYpel + y;
                    GXWGFifo.u8 = _primTextColor.r;
                    GXWGFifo.u8 = _primTextColor.g;
                    GXWGFifo.u8 = _primTextColor.b;
                    GXWGFifo.u8 = _primTextColor.a;
                }
            }
        }
        case ' ':
            x += _primTextXpel;
            break;
        }
        str++;
    }
    return count;
}

static u8* _primChar2Ptr(char c) {
    int idx;
    if (c >= '0' && c <= '9') {
        idx = c - '0';
    } else if (c >= 'A' && c <= 'Z') {
        idx = c - 'A' + 10;
    } else if (c >= 'a' && c <= 'z') {
        idx = c - 'a' + 10;
    } else {
        switch (c) {
        case '-': idx = 0x24; break;
        case '_': idx = 0x25; break;
        case '~': idx = 0x26; break;
        case '>': idx = 0x27; break;
        case '/': idx = 0x28; break;
        case '(': idx = 0x29; break;
        case ')': idx = 0x2a; break;
        case ',': idx = 0x2b; break;
        case '<': idx = 0x2c; break;
        case '+': idx = 0x2d; break;
        case '$': idx = 0x2e; break;
        case '.': idx = 0x2f; break;
        case ':': idx = 0x30; break;
        case '[': idx = 0x31; break;
        case ']': idx = 0x32; break;
        case '=': idx = 0x33; break;
        case '#': idx = 0x34; break;
        case '!': idx = 0x35; break;
        case '\'': idx = 0x36; break;
        case '"': idx = 0x37; break;
        default: idx = 0x25; break;
        }
    }
    return _primLineFont[idx];
}
