#define CAMERA_PATTERN_FLAG_A 0x80
#define CAMERA_PATTERN_FLAG_B 0x100
#define CAMERA_PATTERN_FLAG_C 0x200

WazaCameraPattern* wazaSequenceCameraGetPattern(bool attack, int flags) {
    f32 r = HSD_Randf();
    f32 sum = 0.0f;
    WazaCameraPattern* pattern;
    int num;
    int i;

    if (attack) {
        pattern = attackPatterns;
        num = 8;
        if (flags & CAMERA_PATTERN_FLAG_A) {
            return &attackPatterns[4];
        }
        if (flags & CAMERA_PATTERN_FLAG_B) {
            return &attackPatterns[5];
        }
        if (flags & CAMERA_PATTERN_FLAG_C) {
            return &attackPatterns[6];
        }
    } else {
        pattern = defensePatterns;
        num = 13;
        if (flags & CAMERA_PATTERN_FLAG_A) {
            return &defensePatterns[9];
        }
        if (flags & CAMERA_PATTERN_FLAG_B) {
            return &defensePatterns[10];
        }
        if (flags & CAMERA_PATTERN_FLAG_C) {
            return &defensePatterns[11];
        }
    }
    for (i = 0; i < num; i++, pattern++) {
        sum += pattern->weight;
        if (r < sum) {
            return pattern;
        }
    }
    if (attack) {
        return &attackPatterns[Rand32() % 8];
    }
    return &defensePatterns[Rand32() % 13];
}
